#!/usr/bin/env bash
# Печатает код прямого подключения к серверу разработчика (маршрут «Ебаная Чукотка») или пустую строку.
# Источник: секрет GitHub DEV_DIRECT. Формат: d1:<IP>:<порт>:<sha256 сертификата>:<ключ доступа>.
set -u
RAW="$(printf '%s' "${DEV_DIRECT:-}" | tr -d '[:space:]')"
DC="$(printf '%s' "$RAW" | grep -oE 'd1:[0-9]{1,3}(\.[0-9]{1,3}){3}:[0-9]{1,5}:[0-9a-f]{64}:[0-9a-f]{32}' | head -1 || true)"
if [ -n "$DC" ]; then
  echo "Код «Ебаная Чукотка»: найден, сервер $(printf '%s' "$DC" | cut -d: -f2-3)" >&2
elif [ -n "$RAW" ]; then
  echo "::warning::Код DEV_DIRECT в неверном формате ($(printf '%s' "$RAW" | wc -c) символов) — скопируйте его заново кнопкой «Копировать код «Ебаная Чукотка»»" >&2
else
  echo "Код DEV_DIRECT не задан — маршрута «Ебаная Чукотка» в сборке не будет" >&2
fi
printf '%s' "$DC"
