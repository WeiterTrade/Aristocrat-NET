#!/usr/bin/env bash
# Печатает код подключения к компьютеру разработчика (или пустую строку) и пишет в журнал сборки, что нашёл.
# Источник: секрет GitHub DEV_CODE (переменная окружения), иначе файл dev-code.txt в корне репозитория.
# Код ищется внутри текста, поэтому лишние слова, кавычки и переносы строк не мешают.
# Формат: <56 символов адреса .onion>:<52 символа ключа>.
set -u
RE='[a-z2-7]{56}(\.onion)?:[A-Z2-7]{52}'
SRC="секрет DEV_CODE"
RAW="${DEV_CODE:-}"
if [ -z "$(printf '%s' "$RAW" | tr -d '[:space:]')" ]; then
  SRC="файл dev-code.txt"
  RAW="$(cat "$(dirname "$0")/../dev-code.txt" 2>/dev/null || true)"
fi
DC="$(printf '%s' "$RAW" | tr -d '[:space:]' | grep -oE "$RE" | head -1 || true)"
if [ -n "$DC" ]; then
  echo "Код подключения: найден ($SRC), адрес ${DC:0:6}…${DC:50:6}.onion — режим «Через разработчика» будет в сборке" >&2
elif [ -n "$(printf '%s' "$RAW" | tr -d '[:space:]')" ]; then
  N=$(printf '%s' "$RAW" | tr -d '[:space:]' | wc -c)
  echo "::warning::Код подключения ($SRC) в неверном формате ($N символов) — скопируйте его заново кнопкой «Копировать код подключения»" >&2
else
  echo "::warning::Код подключения не задан (нет секрета DEV_CODE) — режима «Через разработчика» в сборке не будет" >&2
fi
printf '%s' "$DC"
